const rateLimit = require('express-rate-limit');

const isProduction = process.env.NODE_ENV === 'production';

/**
 * محدد محاولات المصادقة (تسجيل الدخول والتسجيل الجديد)
 * يسمح بـ 5 محاولات كحد أقصى لكل 15 دقيقة لمنع هجمات التخمين Brute-Force —
 * لكن هذا الحد الصارم مقصور فعليًا على بيئة الإنتاج. الشرط allow-list صريح على
 * NODE_ENV === 'production' (نفس نمط SESSION_SECRET في config.js) بدل استثناء
 * قيم بعينها كـ'test': أي بيئة غير مُعلَّمة صراحة كإنتاج تحصل على حد أعلى بكثير،
 * فلا تُصطدم ملفات الاختبار التي تفتح عدة جلسات (أدوار/مكاتب مختلفة) بنفس ملف
 * الاختبار بهذا الحد المصمَّم أصلًا لحماية تسجيل الدخول الحقيقي من هجمات خارجية.
 */
const authLimiter = rateLimit({
    windowMs: 15 * 60 * 1000, // 15 دقيقة
    max: isProduction ? 5 : 1000, // 5 محاولات بالإنتاج فقط لكل عنوان IP؛ حد مرتفع خارجه
    message: {
        success: false,
        message: 'لقد تجاوزت الحد الأقصى للمحاولات المسموح بها. يرجى المحاولة مرة أخرى بعد 15 دقيقة لحماية حسابك.'
    },
    standardHeaders: true, // إرجاع معلومات حد المعدل في ترويسات RateLimit-*
    legacyHeaders: false, // إيقاف الترويسات القديمة X-RateLimit-*
});

/**
 * محدد محاولات تغيير كلمة المرور — نفس صرامة authLimiter (5 محاولات/15 دقيقة لكل IP
 * بالإنتاج)، لكن بعدّاد مستقل خاص به. مسار تغيير كلمة المرور يتحقق من current_password
 * عبر bcrypt.compare بنفس حساسية مسار تسجيل الدخول (مهاجم سرق جلسة المستخدم قد يحاول
 * تخمين كلمة سره الحالية للاستيلاء الكامل على الحساب)، فيستحق نفس مستوى الحماية.
 * لكن استخدام عدّاد مستقل (لا نفس authLimiter) متعمّد: محاولات دخول فاشلة لا يجب أن
 * تستهلك من رصيد محاولات تغيير كلمة المرور لمستخدم مسجّل دخوله فعلًا، فكل مسار له
 * نموذج تهديد مختلف يستحق ميزانية محاولات خاصة به. نفس تخفيف NODE_ENV أعلاه ينطبق هنا.
 */
const passwordChangeLimiter = rateLimit({
    windowMs: 15 * 60 * 1000, // 15 دقيقة
    max: isProduction ? 5 : 1000, // 5 محاولات بالإنتاج فقط لكل عنوان IP؛ حد مرتفع خارجه
    message: {
        success: false,
        message: 'لقد تجاوزت الحد الأقصى للمحاولات المسموح بها. يرجى المحاولة مرة أخرى بعد 15 دقيقة لحماية حسابك.'
    },
    standardHeaders: true,
    legacyHeaders: false,
});

/**
 * محدد الطلبات العام للـ API لحماية السيرفر وقاعدة البيانات من هجمات DoS
 * يسمح بـ 100 طلب كحد أقصى لكل 15 دقيقة لكل عنوان IP بالإنتاج. نفس تخفيف NODE_ENV
 * أعلاه ينطبق هنا أيضًا — هذا الحد يصطدم بسهولة بالاختبار اليدوي المتكرر بالمتصفح
 * أو بملفات اختبار تُرسل عشرات الطلبات بنفس beforeAll، دون أن يمثّل ذلك خطر DoS فعليًا.
 */
const apiLimiter = rateLimit({
    windowMs: 15 * 60 * 1000, // 15 دقيقة
    max: isProduction ? 100 : 10000, // 100 طلب بالإنتاج فقط؛ حد مرتفع خارجه
    message: {
        success: false,
        message: 'تم تقييد الطلبات مؤقتاً بسبب كثرة الاستدعاءات المرسلة من هذا الجهاز. يرجى المحاولة لاحقاً.'
    },
    standardHeaders: true,
    legacyHeaders: false,
});

module.exports = {
    authLimiter,
    passwordChangeLimiter,
    apiLimiter
};
